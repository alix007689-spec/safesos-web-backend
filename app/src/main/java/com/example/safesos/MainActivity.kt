enum class SOSState {
    IDLE,
    COUNTDOWN,
    ACTIVATED,
    ACTIVE_EMERGENCY,
    COMPLETED
}

enum class SharingDuration(val label: String, val minutes: Int) {
    ONCE("Share once", 0),
    MIN_15("15 minutes", 15),
    MIN_30("30 minutes", 30),
    HOUR_1("1 hour", 60),
    UNTIL_STOP("Until I stop it", -1)
}

data class EmergencyContact(
    val id: String,
    val name: String,
    val phone: String,
    val relationship: String,
    val isVerified: Boolean = false,
    val isPrimary: Boolean = false
)

data class SOSAlertMessage(
    val senderName: String,
    val timestamp: String,
    val latitude: Double,
    val longitude: Double,
    val accuracy: Float
) {
    // Plain ASCII only: keeps the alert on GSM-7 encoding so it doesn't silently
    // balloon into extra SMS segments (or get mangled) on some carriers.
    fun toFormattedString(): String {
        val mapsUrl = "https://maps.google.com/?q=$latitude,$longitude"
        return """
            EMERGENCY ALERT

            I may need help.

            Name: $senderName
            Time: $timestamp
            Location: $mapsUrl (+/-${accuracy.toInt()}m)

            Please contact me or call emergency services if necessary.

            This message was automatically generated by SafeSOS.
        """.trimIndent()
    }
}


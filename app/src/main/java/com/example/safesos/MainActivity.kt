class SecureStorage(context: Context) {
    private val masterKey = MasterKey.Builder(context)
        .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
        .build()

    private val prefs = EncryptedSharedPreferences.create(
        context,
        "safe_sos_encrypted_prefs",
        masterKey,
        EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
        EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM
    )

    fun saveContacts(contacts: List<EmergencyContact>) {
        val array = JSONArray()
        contacts.forEach { contact ->
            val obj = JSONObject().apply {
                put("id", contact.id)
                put("name", contact.name)
                put("phone", contact.phone)
                put("relationship", contact.relationship)
                put("isVerified", contact.isVerified)
                put("isPrimary", contact.isPrimary)
            }
            array.put(obj)
        }
        prefs.edit().putString("key_contacts", array.toString()).apply()
    }

    fun getContacts(): List<EmergencyContact> {
        val jsonString = prefs.getString("key_contacts", null) ?: return emptyList()
        val list = mutableListOf<EmergencyContact>()
        val array = JSONArray(jsonString)
        for (i in 0 until array.length()) {
            val obj = array.getJSONObject(i)
            list.add(
                EmergencyContact(
                    id = obj.getString("id"),
                    name = obj.getString("name"),
                    phone = obj.getString("phone"),
                    relationship = obj.getString("relationship"),
                    isVerified = obj.getBoolean("isVerified"),
                    isPrimary = obj.getBoolean("isPrimary")
                )
            )
        }
        return list
    }

    fun saveUserName(name: String) = prefs.edit().putString("key_user_name", name).apply()
    fun getUserName(): String = prefs.getString("key_user_name", "User") ?: "User"
}


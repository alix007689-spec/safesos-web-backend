class SOSViewModel(private val applicationContext: Context) : ViewModel() {
    private val secureStorage = SecureStorage(applicationContext)
    private val fusedLocationClient = LocationServices.getFusedLocationProviderClient(applicationContext)

    private val _sosState = MutableStateFlow(SOSState.IDLE)
    val sosState: StateFlow<SOSState> = _sosState.asStateFlow()

    private val _countdownProgress = MutableStateFlow(0f)
    val countdownProgress: StateFlow<Float> = _countdownProgress.asStateFlow()

    private val _contacts = MutableStateFlow<List<EmergencyContact>>(emptyList())
    val contacts: StateFlow<List<EmergencyContact>> = _contacts.asStateFlow()

    private val _currentLocationText = MutableStateFlow("Obtaining location...")
    val currentLocationText: StateFlow<String> = _currentLocationText.asStateFlow()

    private val _selectedDuration = MutableStateFlow(SharingDuration.MIN_15)
    val selectedDuration: StateFlow<SharingDuration> = _selectedDuration.asStateFlow()

    private val _statusLog = MutableStateFlow<List<String>>(emptyList())
    val statusLog: StateFlow<List<String>> = _statusLog.asStateFlow()

    private var countdownJob: Job? = null

    init {
        _contacts.value = secureStorage.getContacts()
    }

    fun setSharingDuration(duration: SharingDuration) {
        _selectedDuration.value = duration
    }

    fun addContact(name: String, phone: String, relationship: String) {
        val newContact = EmergencyContact(
            id = System.currentTimeMillis().toString(),
            name = name,
            phone = phone,
            relationship = relationship,
            isVerified = true, // Auto-verified for demo simplicity
            isPrimary = _contacts.value.isEmpty()
        )
        val updated = _contacts.value + newContact
        _contacts.value = updated
        secureStorage.saveContacts(updated)
    }

    fun removeContact(id: String) {
        val updated = _contacts.value.filter { it.id != id }
        _contacts.value = updated
        secureStorage.saveContacts(updated)
    }

    fun startSOSPress() {
        if (_sosState.value != SOSState.IDLE) return

        // Guard against a stray job from a previous press still running.
        countdownJob?.cancel()

        _sosState.value = SOSState.COUNTDOWN
        countdownJob = viewModelScope.launch {
            val totalTime = 2000L // 2-second hold threshold
            val interval = 50L
            var elapsed = 0L

            while (elapsed < totalTime) {
                delay(interval)
                elapsed += interval
                _countdownProgress.value = elapsed.toFloat() / totalTime.toFloat()
            }

            triggerSOSActivation()
        }
    }

    fun cancelSOSPress() {
        if (_sosState.value == SOSState.COUNTDOWN) {
            countdownJob?.cancel()
            _sosState.value = SOSState.IDLE
            _countdownProgress.value = 0f
        }
    }

    private fun triggerSOSActivation() {
        _sosState.value = SOSState.ACTIVATED
        _statusLog.value = listOf("Initializing emergency protocol...")

        triggerVibration()

        viewModelScope.launch {
            appendLog("Acquiring GPS Signal...")
            val location = fetchCurrentLocation()

            val senderName = secureStorage.getUserName()
            val timeStr = java.text.SimpleDateFormat("HH:mm", java.util.Locale.getDefault()).format(java.util.Date())

            val alert = SOSAlertMessage(
                senderName = senderName,
                timestamp = timeStr,
                latitude = location?.latitude ?: 0.0,
                longitude = location?.longitude ?: 0.0,
                accuracy = location?.accuracy ?: 0f
            )

            if (location != null) {
                _currentLocationText.value =
                    "Lat: ${String.format("%.4f", location.latitude)}, Lon: ${String.format("%.4f", location.longitude)}"
                appendLog("[OK] Location obtained (+/-${location.accuracy.toInt()}m)")
            } else {
                _currentLocationText.value = "Location unavailable (Using fallback)"
                appendLog("[WARN] GPS fallback active")
            }

            appendLog("Evaluating network routes...")
            dispatchEmergencyAlert(alert)
        }
    }

    private suspend fun fetchCurrentLocation(): android.location.Location? {
        return suspendCancellableCoroutine { continuation ->
            val fineGranted = ContextCompat.checkSelfPermission(
                applicationContext, Manifest.permission.ACCESS_FINE_LOCATION
            ) == PackageManager.PERMISSION_GRANTED
            val coarseGranted = ContextCompat.checkSelfPermission(
                applicationContext, Manifest.permission.ACCESS_COARSE_LOCATION
            ) == PackageManager.PERMISSION_GRANTED

            if (!fineGranted && !coarseGranted) {
                continuation.resume(null)
                return@suspendCancellableCoroutine
            }

            // Only ask for high accuracy if we actually hold the fine-location permission;
            // otherwise fall back to a coarser (but still usable) accuracy request.
            val priority = if (fineGranted) Priority.PRIORITY_HIGH_ACCURACY else Priority.PRIORITY_BALANCED_POWER_ACCURACY

            val cts = CancellationTokenSource()
            continuation.invokeOnCancellation { cts.cancel() }

            fusedLocationClient.getCurrentLocation(priority, cts.token)
                .addOnSuccessListener { location ->
                    if (continuation.isActive) continuation.resume(location)
                }
                .addOnFailureListener {
                    if (continuation.isActive) continuation.resume(null)
                }
        }
    }

    private fun dispatchEmergencyAlert(alert: SOSAlertMessage) {
        val isNetworkAvailable = checkNetworkAvailability()

        if (isNetworkAvailable) {
            appendLog("[OK] Internet available: Dispatching IP Alert")
            // IP payload delivery logic goes here
            finalizeActivation()
        } else {
            appendLog("[WARN] No Internet: Falling back to Cellular SMS")
            if (ContextCompat.checkSelfPermission(applicationContext, Manifest.permission.SEND_SMS) == PackageManager.PERMISSION_GRANTED) {
                sendSMSAlerts(alert.toFormattedString())
                appendLog("[OK] SMS Alerts dispatched to contacts")
            } else {
                appendLog("[ERROR] SMS permission missing! Displaying emergency instructions.")
            }
            finalizeActivation()
        }
    }

    private fun sendSMSAlerts(message: String) {
        // getSystemService(SmsManager::class.java) requires API 31+; fall back for older devices.
        val smsManager: SmsManager = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            applicationContext.getSystemService(SmsManager::class.java)
        } else {
            @Suppress("DEPRECATION")
            SmsManager.getDefault()
        }

        val parts: ArrayList<String> = smsManager.divideMessage(message)

        _contacts.value.forEach { contact ->
            try {
                if (parts.size > 1) {
                    smsManager.sendMultipartTextMessage(contact.phone, null, parts, null, null)
                } else {
                    smsManager.sendTextMessage(contact.phone, null, message, null, null)
                }
            } catch (e: Exception) {
                e.printStackTrace()
            }
        }
    }

    private fun finalizeActivation() {
        _sosState.value = SOSState.ACTIVE_EMERGENCY
        appendLog("SOS ACTIVE - Live Monitoring Engaged")
    }

    fun stopSOS() {
        _sosState.value = SOSState.COMPLETED
        _countdownProgress.value = 0f
        appendLog("Emergency sequence terminated by user.")
    }

    fun resetToIdle() {
        _sosState.value = SOSState.IDLE
        _statusLog.value = emptyList()
    }

    private fun appendLog(msg: String) {
        _statusLog.value = _statusLog.value + msg
    }

    private fun checkNetworkAvailability(): Boolean {
        val cm = applicationContext.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
        val capabilities = cm.getNetworkCapabilities(cm.activeNetwork)
        return capabilities?.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET) == true
    }

    private fun triggerVibration() {
        val vibrator = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            val vibratorManager = applicationContext.getSystemService(Context.VIBRATOR_MANAGER_SERVICE) as VibratorManager
            vibratorManager.defaultVibrator
        } else {
            @Suppress("DEPRECATION")
            applicationContext.getSystemService(Context.VIBRATOR_SERVICE) as Vibrator
        }
        vibrator.vibrate(VibrationEffect.createOneShot(500, VibrationEffect.DEFAULT_AMPLITUDE))
    }
}

class SOSViewModelFactory(private val context: Context) : ViewModelProvider.Factory {
    override fun <T : ViewModel> create(modelClass: Class<T>): T {
        if (modelClass.isAssignableFrom(SOSViewModel::class.java)) {
            @Suppress("UNCHECKED_CAST")
            return SOSViewModel(context.applicationContext) as T
        }
        throw IllegalArgumentException("Unknown ViewModel class: ${modelClass.name}")
    }
}

